CREATE OR REPLACE FUNCTION mlr.seed_igc_store(npc int, items jsonb) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
  luck_type   uuid := '3e3e9be8-4e16-4f27-a7cf-986d48454d76';
  option_type uuid := 'f193f91e-86d7-4456-add8-a3667e731303';
